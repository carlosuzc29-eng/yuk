/**
 * Catálogo de ejercicios de YUK.
 * Selección basada en la práctica actual de hipertrofia y fuerza: básicos con barra,
 * variantes estables en máquina y polea (mayor tensión en posiciones alargadas),
 * y progresiones con peso corporal para entrenar en casa.
 */

type Opts = { unilateral?: boolean; timed?: boolean };

function e(
  id: string,
  name: string,
  equipment: ExerciseEquipment,
  pattern: MovementPattern,
  mechanics: Mechanics,
  level: ExperienceLevel,
  primary: MuscleId[],
  secondary: MuscleId[],
  avoidIf: InjuryType[],
  steps: string[],
  mistakes: string[],
  beginnerTip: string,
  opts: Opts = {}
): Exercise {
  return {
    id,
    name,
    equipment,
    pattern,
    mechanics,
    level,
    primary,
    secondary,
    avoidIf,
    steps,
    mistakes,
    beginnerTip,
    ...opts,
  };
}

