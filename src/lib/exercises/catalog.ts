export interface ExerciseFilter {
  muscle?: MuscleId | null;
  modality?: Modality | null;
  search?: string;
  allowedEquipment?: ExerciseEquipment[] | null;
  excludeInjuries?: string[];
  includeSecondary?: boolean;
}

function normalize(s: string): string {
  return s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '');
}

export function filterExercises(filter: ExerciseFilter): Exercise[] {
  const q = filter.search ? normalize(filter.search.trim()) : '';
  return EXERCISES.filter((x) => {
    if (filter.muscle) {
      const hit =
        x.primary.includes(filter.muscle) ||
        (filter.includeSecondary && x.secondary.includes(filter.muscle));
      if (!hit) return false;
    }
    if (filter.modality && modalityOf(x.equipment) !== filter.modality) return false;
    if (filter.allowedEquipment && !filter.allowedEquipment.includes(x.equipment)) return false;
    if (filter.excludeInjuries?.length && x.avoidIf.some((i) => filter.excludeInjuries!.includes(i)))
      return false;
    if (q && !normalize(x.name).includes(q)) return false;
    return true;
  }).sort((a, b) => {
    if (!filter.muscle) return 0;
    const pa = a.primary[0] === filter.muscle ? 0 : a.primary.includes(filter.muscle) ? 1 : 2;
    const pb = b.primary[0] === filter.muscle ? 0 : b.primary.includes(filter.muscle) ? 1 : 2;
    return pa - pb;
  });
}
